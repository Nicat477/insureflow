export function translate(language: Language, text: string): string {
  const dictionary = language === 'ru' ? ruMessages : language === 'az' ? azMessages : undefined
  return dictionary && Object.prototype.hasOwnProperty.call(dictionary, text) ? dictionary[text] : text
}
export function translateError(language: Language, message: string): string {
  if (language === 'en') return message
  const dictionary = language === 'ru' ? ruMessages : azMessages
  return Object.prototype.hasOwnProperty.call(dictionary, message) ? dictionary[message] : dictionary['Something went wrong. Please retry.']
}
export function formatMoney(language: Language, value: number): string {
  return new Intl.NumberFormat(language === 'az' ? 'az-AZ' : language === 'ru' ? 'ru-RU' : 'en-AZ', { style: 'currency', currency: 'AZN', maximumFractionDigits: 2 }).format(value)
}
export function formatDate(language: Language, value: string): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return value
  const date = new Date(value + 'T00:00:00Z')
  return Number.isNaN(date.getTime()) ? value : new Intl.DateTimeFormat(language === 'az' ? 'az-AZ' : language === 'ru' ? 'ru-RU' : 'en-GB', { dateStyle: 'medium', timeZone: 'UTC' }).format(date)
}
